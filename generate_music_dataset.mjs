const headers = [
  "rank", "song", "artist", "artist_country", "language", "release_year", "decade",
  "genre", "album", "duration_seconds", "bpm", "energy", "danceability",
  "valence", "acousticness", "explicit", "my_listens", "youtube_views_estimate",
  "spotify_streams_estimate", "favorite_score", "skip_rate", "first_added_date"
];

const esc = (value) => `"${String(value).replaceAll('"', '""')}"`;
const clamp = (value, min, max) => Math.max(min, Math.min(max, value));
const hash = (text) => [...text].reduce((sum, ch) => (sum * 31 + ch.charCodeAt(0)) % 100000, 7);

const makeRows = (songList, rankOffset = 0, defaultLanguage = "English") => songList.slice(0, 100).map((row, index) => {
  const [song, artist, year, country, genre, album, duration] = row;
  const h = hash(`${song}${artist}`);
  const language = defaultLanguage !== "English"
    ? defaultLanguage
    : new Set(["Despacito", "Macarena (Bayside Boys Mix)"]).has(song)
    ? "Spanish"
    : new Set(["Hips Don't Lie", "Whenever, Wherever", "Livin' la Vida Loca"]).has(song)
      ? "English/Spanish"
      : "English";
  const popBias = Math.max(0, 100 - index);
  const energy = +(0.42 + ((h % 48) / 100)).toFixed(2);
  const danceability = +(0.35 + (((h >> 2) % 58) / 100)).toFixed(2);
  const valence = +(0.25 + (((h >> 4) % 70) / 100)).toFixed(2);
  const acousticness = +(0.05 + (((h >> 6) % 65) / 100)).toFixed(2);
  const bpm = 78 + (h % 88);
  const myListens = 8 + ((h + index * 37) % 185);
  const youtubeViews = Math.round((35 + popBias * 1.8 + (h % 70)) * 1_000_000);
  const spotifyStreams = Math.round((55 + popBias * 5.1 + (h % 180)) * 1_000_000);
  const favoriteScore = +(5.8 + ((h % 40) / 10)).toFixed(1);
  const skipRate = +(0.04 + (((h >> 3) % 23) / 100)).toFixed(2);
  const addedMonth = String(1 + (h % 12)).padStart(2, "0");
  const addedDay = String(1 + (h % 27)).padStart(2, "0");
  return [
    rankOffset + index + 1, song, artist, country, language, year, `${Math.floor(year / 10) * 10}s`,
    genre, album, duration, bpm, energy, danceability, valence, acousticness,
    h % 5 === 0 ? "TRUE" : "FALSE", myListens, youtubeViews, spotifyStreams,
    favoriteScore, skipRate, `2025-${addedMonth}-${addedDay}`
  ];
});

const rows = [
  ...makeRows(songs, 0, "English"),
  ...makeRows(bollywoodSongs, 100, "Hindi")
  , ...makeRows(teluguSongs, 200, "Telugu")
  , ...makeRows(tamilSongs, 300, "Tamil")
];

const csv = [
  headers.map(esc).join(","),
  ...rows.map((row) => row.map(esc).join(","))
].join("\n") + "\n";

writeFileSync("music_visualizer_songs.csv", csv, "utf8");
